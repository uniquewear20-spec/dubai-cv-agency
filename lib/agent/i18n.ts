const list = (xs: string[], and: string) => (xs.length <= 1 ? xs.join("") : `${xs.slice(0, -1).join(", ")} ${and} ${xs[xs.length - 1]}`);
/** Arabic list: "أ، ب وج" with the conjunction joined to the last item. */
export const arList = (xs: string[]) => (xs.length <= 1 ? xs.join("") : `${xs.slice(0, -1).join("، ")} و${xs[xs.length - 1]}`);
/** A list of names in the given language: "A, B and C", "A, B et C", "أ، ب وج". */
export const nameList = (xs: string[], lang: "en" | "fr" | "ar") => (lang === "ar" ? arList(xs) : list(xs, lang === "fr" ? "et" : "and"));

